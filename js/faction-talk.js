export const aboutFaction = f => voices[f.id][0];
export function factionOptions(f, who=f.key||'clan_'+f.id) {
  const v=voices[f.id];
  return [['이곳에 대해 묻는다',()=>say(who,v[0])],['일상 대화를 나눈다',()=>{
    const visits=G.S.factionChats ||= {}, n=visits[who]||0;
    visits[who]=n+1; return say(who,v[1+n%(v.length-1)]);
  }]];
}
export function tutorSpeaker(f, name, elder) {
  const id='tutor_'+f.id+(elder?'_elder':'');
  WHO[id]={name:f.name+' '+name,face:elder?'OldMan':'Samurai',art:elder?'elder':'disc'};
  return id;
}
export function standingLabel(f) {
  const r=standing(f);
  return f.who+' · '+r.position+' · '+NAME[r.realm];
}
