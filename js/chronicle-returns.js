export async function chapterEcho(no){
  const s=G.S,p=parts[no],d=s.chronicle;
  if(!d||!p||s.flags['heardRoad'+no]||!Object.hasOwn(d.done,p[0]))return;
  s.flags['heardRoad'+no]=true;await narr(p[1+d.done[p[0]]]);
}
export function returnWitnesses(map){
  const s=G.S,d=s.chronicle;if(!d)return [];
  return witnesses.filter(([key,place])=>map===place&&Object.hasOwn(d.done,key)).map(([key,,x,y,name,spr,lines])=>{
    const id='road_witness_'+key;WHO[id]??={name,face:spr};
    return {id,spr,x,y,dir:0,hint:name,mark:()=>!s.flags[id],talk:async()=>{await say(id,lines[d.done[key]]);s.flags[id]=true;}};
  });
}
