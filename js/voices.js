// 고을 하나에 같은 사람이 겹치지 않게, 도트에 어울리는 사람을 정해 준다. 같은 고을이면 늘 같은 사람이다
const seed = s => { let n = 7; for (const c of s) n = (n * 31 + c.charCodeAt(0)) % 233280; return () => (n = (n * 9301 + 49297) % 233280) / 233280; };
export function assign(map, sprs) {
  const R = seed(map), used = new Set(), keys = Object.keys(PERSONAS);
  return sprs.map(spr => {
    const fit = keys.filter(k => PERSONAS[k].fits.includes(spr)), free = fit.filter(k => !used.has(k)), L = free.length ? free : fit.length ? fit : keys, k = L[Math.floor(R() * L.length)]; used.add(k);
    const P = PERSONAS[k], who = P.who[Math.floor(R() * P.who.length)] + (P.sur ? ` ${SURNAME[Math.floor(R() * SURNAME.length)]}씨` : '');
    return { key: k, p: P, who, spr: P.spr || spr };
  });
}

