function context(map, place) {
  const S = G.S, fr = S.fr, v = { p: place || '', ttl: S.title && S.title !== '떠돌이 낭인' ? S.title : S.name }, on = {};
  const c = G.saga?.talkCtx?.(map); if (c) { Object.assign(v, c.v); Object.assign(on, c.on); }
  if (fr) { if ((fr.infamy || 0) >= 40) on.feared = 1; else if ((fr.fame || 0) >= 120) on.famous = 1; }
  if (S.flags?.saga_champ) on.champ = 1;
  return { v, on };
}
const fill = (t, v) => t.replace(/\{(\w+)(?:\|([^}]+))?\}/g, (m, k, j) => j ? josa(v[k], j) : v[k]);
const ok = (t, v) => [...t.matchAll(/\{(\w+)/g)].every(m => v[m[1]] !== undefined && v[m[1]] !== null && v[m[1]] !== '');
// 사람마다 오늘 몇 번 말했는지, 지난 화제가 뭐였는지, 화제마다 어디까지 말했는지
const MEM = new Map();
export function line(key, P, { map, place, local = [] } = {}) {
  const S = G.S, day = S.day || 1, m = MEM.get(key) || { day, n: 0, last: null, idx: {} }; if (m.day !== day) { m.day = day; m.n = 0; } MEM.set(key, m);
  const { v, on } = context(map, place), night = !!S.flags?.night; let morning = false; try { morning = !night && S.mode === 'free' && /아침/.test(G.free.period()); } catch (e) { }
  const W = [];  // [가중치, 화제]
  if (m.n >= 2) W.push([5, 'again']);
  const meTopic = on.feared ? 'feared' : on.savior ? 'savior' : on.champ && m.n === 0 && Math.random() < .5 ? 'champ' : on.famous ? 'famous' : null;
  if (meTopic) W.push([m.n === 0 ? 4 : 1, meTopic]);
  for (const t of ['tourNotice', 'tourDone', 'jswOmen', 'jswWar', 'jswAfter', 'demonOmen', 'league', 'occOther', 'demonAfter']) if (on[t]) W.push([on[t] * (m.n === 0 ? 1.8 : 1.2), t]);  // 큰일이 있으면 그 얘기부터 꺼낸다
  if (morning) W.push([.6, 'morning']); if (night) W.push([.9, 'night']);
  W.push([2.5, 'life']); if (local.length) W.push([1.5, 'local']);
  const pool = t => (t === 'local' ? local : P[t] || []).filter(x => ok(x, v));
  let cand = W.filter(([, t]) => t !== m.last && pool(t).length); if (!cand.length) cand = W.filter(([, t]) => pool(t).length);
  let r = Math.random() * cand.reduce((a, [w]) => a + w, 0), topic = cand[cand.length - 1][1]; for (const [w, t] of cand) { if ((r -= w) <= 0) { topic = t; break; } }
  const L = pool(topic), i = m.idx[topic] || 0; m.idx[topic] = i + 1; m.last = topic; m.n++;
  return fill(L[i % L.length], v);
}
